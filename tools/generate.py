"""Makes data/recipes.lua from the wiki snapshot, the overrides and the config names (ADR 0015).

Command: python3 tools/generate.py
It reads tools/wiki-snapshot.json, tools/overrides.lua and tools/config-names.lua.
It sends no requests. It needs lua5.4 and stylua.
"""

import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SNAPSHOT_PATH = os.path.join(HERE, "wiki-snapshot.json")
OVERRIDES_PATH = os.path.join(HERE, "overrides.lua")
CONFIG_NAMES_PATH = os.path.join(HERE, "config-names.lua")
LUA_TO_JSON = os.path.join(HERE, "lua_to_json.lua")
STYLUA_CONFIG = os.path.join(ROOT, "stylua.toml")
OUTPUT_PATH = os.path.join(ROOT, "data", "recipes.lua")

TESTED_METHODS = ("probe", "manual")
HEADER = (
    "-- Generated by tools/generate.py. Do not edit. Change tools/overrides.lua and run the generator again.\n"
    "-- Recipe data from the RuneScape Wiki (https://runescape.wiki), CC BY-NC-SA 3.0.\n"
)
# The order of the fields of a Recipe in data/recipes.lua.
RECIPE_FIELDS = ["id", "wiki", "verb", "output", "otherOutputs", "inputs", "skills", "actionLimit", "actionTime"]


class GenerateError(Exception):
    pass


class NotANumber(Exception):
    pass


def as_map(value):
    """lua_to_json gives an empty table as an empty list."""
    return value if isinstance(value, dict) else {}


def whole_number(text, what):
    if isinstance(text, int):
        return text
    if isinstance(text, str) and re.fullmatch(r"\d+", text.strip()):
        return int(text)
    raise NotANumber(f"{what} {text!r} is not a whole number")


def recipe_id(output, quantity, inputs):
    base = f"{output}_x{quantity}"
    names = sorted({entry["item"] for entry in inputs})
    if not names:
        return base
    return base + "_" + hashlib.sha256(",".join(names).encode()).hexdigest()[:6]


def check_override(where, field, entry, errors):
    """Each override gives a reason. A tested value also gives the date and the method."""
    if not isinstance(entry, dict) or not isinstance(entry.get("reason"), str) or not entry["reason"]:
        errors.append(f"The override {field} of {where} has no reason.")
        return
    tested = entry.get("tested")
    if tested is None:
        return
    if not isinstance(tested.get("date"), str):
        errors.append(f"The tested override {field} of {where} has no date.")
    if tested.get("method") not in TESTED_METHODS:
        errors.append(
            f"The tested override {field} of {where} has the method {tested.get('method')}."
            f" Use {' or '.join(TESTED_METHODS)}."
        )


class Items:
    """Finds the config name of a wiki item from its page and name."""

    def __init__(self, infobox, item_overrides, config_names, errors):
        self.ids = {}
        for row in infobox:
            key = (row.get("page_name"), row.get("item_name"))
            self.ids.setdefault(key, set()).update(row.get("item_id") or [])
        self.overrides = item_overrides
        self.config_names = config_names
        self.errors = errors

    def config_name(self, entry):
        name = entry["name"]
        page = entry.get("page", name)
        override = self.overrides.get(name)
        if override is not None:
            ids = [override.get("id")]
        else:
            ids = sorted(self.ids.get((page, name), ()))
        if not ids:
            self.errors.append(f"The item {name} (page {page}) has no item ID in the infobox_item rows.")
            return None
        if len(ids) > 1:
            listed = ", ".join(str(i) for i in ids)
            self.errors.append(
                f"The item {name} (page {page}) has more than one item ID: {listed}."
                " Choose one in the items table of tools/overrides.lua."
            )
            return None
        known = self.config_names.get(ids[0])
        if known is None:
            self.errors.append(f"The item {name} has the item ID {ids[0]}, which is not in tools/config-names.lua.")
            return None
        return known["configName"]


def entries(items, raw):
    """Gives { item, count } for each wiki entry. A count that is not a whole number raises NotANumber."""
    result = []
    for entry in raw:
        count = whole_number(entry.get("quantity"), "The quantity of " + entry["name"])
        result.append({"item": items.config_name(entry), "count": count})
    return result


def generate(snapshot, overrides, config_names):
    """Gives the data of data/recipes.lua and a list of warnings. Raises GenerateError with all errors."""
    errors, warnings = [], []
    recipe_overrides = as_map(overrides.get("recipes"))
    item_overrides = as_map(overrides.get("items"))
    for name, entry in item_overrides.items():
        check_override("the item " + name, "id", entry, errors)
    for rid, fields in recipe_overrides.items():
        for field, entry in as_map(fields).items():
            check_override("the Recipe " + rid, field, entry, errors)
    items = Items(snapshot["infobox_item"], item_overrides, config_names, errors)

    recipes, seen = {}, set()
    for row in snapshot["recipe"]:
        page = row["page_name"]
        production = row["production_json"]
        outputs = production.get("outputs") or []
        try:
            action_time = whole_number(production.get("ticks"), "The ticks")
            skills = [
                {"skill": skill["name"].upper(), "level": whole_number(skill.get("level"), "The level")}
                for skill in production.get("skills", [])
            ]
            made = entries(items, outputs)
            inputs = entries(items, production.get("materials", []))
        except NotANumber as reason:
            warnings.append(f"Skipped a row of the wiki page {page}: {reason}.")
            continue
        if not made:
            errors.append(f"A row of the wiki page {page} has no Output.")
            continue
        if any(entry["item"] is None for entry in made + inputs):
            continue

        output = made[0]
        rid = recipe_id(output["item"], output["count"], inputs)
        if rid in seen:
            errors.append(f"Two Recipes have the id {rid} (wiki page {page}).")
            continue
        seen.add(rid)
        fields = as_map(recipe_overrides.get(rid))
        if "skip" in fields:
            continue

        verb = production.get("facility") or fields.get("verb", {}).get("value")
        if verb is None:
            errors.append(f"The Recipe {rid} has no verb. The row has no facility. Give a verb in tools/overrides.lua.")
        action_limit = fields.get("actionLimit", {}).get("value")
        if action_limit is None:
            errors.append(f"The Recipe {rid} has no Action limit. Give it in tools/overrides.lua.")

        recipes.setdefault(output["item"], []).append(
            {
                "id": rid,
                "wiki": page,
                "verb": verb,
                "output": output["count"],
                "otherOutputs": made[1:],
                "inputs": inputs,
                "skills": skills,
                "actionLimit": action_limit,
                "actionTime": action_time,
            }
        )

    if errors:
        raise GenerateError("\n".join(errors))
    for item_recipes in recipes.values():
        item_recipes.sort(key=lambda r: r["id"])
    return {"recipes": recipes}, warnings


IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")
LUA_KEYWORDS = {
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in",
    "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
}  # fmt: skip


def lua_string(text):
    return json.dumps(text, ensure_ascii=False)


def lua_key(key):
    if IDENTIFIER.match(key) and key not in LUA_KEYWORDS:
        return key
    return "[" + lua_string(key) + "]"


def field_order(table):
    if set(table) <= set(RECIPE_FIELDS):
        return [f for f in RECIPE_FIELDS if f in table]
    return sorted(table)


def lua_value(value, indent=""):
    inner = indent + "    "
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, list):
        if not value:
            return "{}"
        return "{\n" + "".join(inner + lua_value(v, inner) + ",\n" for v in value) + indent + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = (inner + lua_key(k) + " = " + lua_value(value[k], inner) + ",\n" for k in field_order(value))
        return "{\n" + "".join(lines) + indent + "}"
    raise GenerateError(f"A value of type {type(value).__name__} cannot be Lua.")


def stylua(text):
    """Formats the text with stylua until it does not change. One pass does not always give stable output."""
    for _ in range(5):
        result = subprocess.run(
            ["stylua", "--config-path", STYLUA_CONFIG, "-"], input=text, capture_output=True, text=True
        )
        if result.returncode != 0:
            raise GenerateError("stylua failed: " + result.stderr)
        if result.stdout == text:
            return text
        text = result.stdout
    raise GenerateError("stylua does not give stable output.")


def render(data):
    return stylua(HEADER + "return " + lua_value(data) + "\n")


def load_lua(path):
    result = subprocess.run(["lua5.4", LUA_TO_JSON, path], capture_output=True, text=True)
    if result.returncode != 0:
        raise GenerateError(f"Cannot read {os.path.basename(path)}: {result.stderr.strip()}")
    return json.loads(result.stdout)


def read_config_names(path):
    return {int(key): value for key, value in as_map(load_lua(path)).items()}


def main():
    try:
        with open(SNAPSHOT_PATH, encoding="utf-8") as file:
            snapshot = json.load(file)
        overrides = as_map(load_lua(OVERRIDES_PATH))
        config_names = read_config_names(CONFIG_NAMES_PATH)
        data, warnings = generate(snapshot, overrides, config_names)
        text = render(data)
    except GenerateError as error:
        print("Error: " + str(error).replace("\n", "\nError: "), file=sys.stderr)
        return 1
    for warning in warnings:
        print("Warning: " + warning, file=sys.stderr)
    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="\n") as file:
        file.write(text)
    print(f"Wrote {sum(len(r) for r in data['recipes'].values())} Recipes to data/recipes.lua.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
